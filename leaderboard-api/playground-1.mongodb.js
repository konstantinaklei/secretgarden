const ScoreSchema = new mongoose.Schema({
    name: {
        type: String,
        required: true,
        trim: true, // Αφαιρεί τα κενά από την αρχή/τέλος
        maxlength: 15 // Μέγιστο μήκος ονόματος
    },
    score: {
        type: Number,
        required: true,
        default: 0
    },
    date: {
        type: Date,
        default: Date.now // Αυτόματο timestamp
    }
});
// ROUTE 1: Αποστολή νέου σκορ (POST /api/scores)
app.post('/api/scores', async (req, res) => {
    try {
        // Τα δεδομένα έρχονται από το σώμα (body) του HTTP request
        const { name, score } = req.body;
        
        // Δημιουργία νέου αντικειμένου Score
        const newScore = new Score({ name, score });
        
        // Αποθήκευση στη MongoDB
        await newScore.save();
        
        // Απάντηση στην Godot ότι ήταν επιτυχής (HTTP 201 Created)
        res.status(201).send({ message: "Score saved!", scoreId: newScore._id });
        
    } catch (error) {
        // Επιστροφή σφάλματος αν κάτι πάει στραβά
        console.error("Error saving score:", error.message);
        res.status(400).send({ message: "Invalid data submitted.", error: error.message });
    }
});

// ROUTE 2: Λήψη του Leaderboard (GET /api/scores)
app.get('/api/scores', async (req, res) => {
    try {
        // Βρίσκει τα 10 καλύτερα σκορ, ταξινομημένα:
        // 1. score (φθίνουσα: -1)
        // 2. date (αύξουσα: 1) - Για tie-breaker
        const topScores = await Score.find()
            .sort({ score: -1, date: 1 }) 
            .limit(10) // Περιορίζει στα 10
            .select('name score'); // Επιστρέφει μόνο τα πεδία name και score
        
        // Επιστροφή των σκορ ως JSON
        res.status(200).json(topScores);
    } catch (error) {
        console.error("Error fetching scores:", error.message);
        res.status(500).send({ message: "Error retrieving leaderboard." });
    }
});
